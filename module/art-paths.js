/**
 * A Map whose mutators throw.
 *
 * @param {Array<[string, string]>} entries The old and new path of each image.
 * @returns {ReadonlyMap<string, string>} The frozen map.
 */
function readOnlyMap(entries) {
    const map = new Map(entries);
    for (const method of ["set", "delete", "clear"]) {
        Object.defineProperty(map, method, {
            value: () => {
                throw new TypeError("ART_PATHS is read-only");
            },
        });
    }
    return Object.freeze(map);
}
